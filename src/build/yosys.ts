/**
 * Turn a validated project + board into a Yosys synthesis run.
 *
 * The plan is a small `.ys` script written to `build/yosys/synth.ys` plus the
 * argument array to invoke yosys with. Writing a script file (rather than a
 * pile of `-p` commands) keeps the run inspectable: you can open it, tweak it,
 * and re-run yosys by hand exactly as OpenFPGA Deck does.
 *
 * Pure — no filesystem, no VS Code — so the generated script is unit-tested.
 */

import * as path from 'node:path';
import type { Board } from '../boards/schema';
import type { FpgaProject } from '../project/schema';
import { buildLayout, type BuildLayout } from './layout';

/** `read_verilog` reads Verilog; `-sv` only adds SystemVerilog syntax on top. */
const SYSTEMVERILOG_RE = /\.(sv|svh)$/i;
const VERILOG_RE = /\.(v|vh)$/i;

export interface YosysPlan {
	/** Absolute path of the script to write. */
	readonly scriptPath: string;
	/** Path of the script relative to the project root (POSIX), for messages. */
	readonly scriptRelPath: string;
	readonly scriptText: string;
	/** Absolute path of the JSON netlist yosys will produce. */
	readonly netlistPath: string;
	readonly netlistRelPath: string;
	/** Argument array for yosys (executable resolved by the caller). */
	readonly args: readonly string[];
}

export type YosysPlanResult =
	| { readonly ok: true; readonly plan: YosysPlan }
	| { readonly ok: false; readonly errors: readonly string[] };

export function planYosys(
	project: FpgaProject,
	board: Board,
	projectRoot: string,
	layout: BuildLayout = buildLayout(projectRoot),
): YosysPlanResult {
	const errors: string[] = [];

	const readLines: string[] = [];
	for (const source of project.sources) {
		if (SYSTEMVERILOG_RE.test(source)) {
			readLines.push(`read_verilog -sv ${toUnix(source)}`);
		} else if (VERILOG_RE.test(source)) {
			readLines.push(`read_verilog ${toUnix(source)}`);
		} else {
			errors.push(
				`Source "${source}" is not Verilog or SystemVerilog. ` +
					'VHDL synthesis (via the GHDL plugin) is not wired up yet.',
			);
		}
	}
	if (readLines.length === 0 && errors.length === 0) {
		errors.push('The project lists no HDL sources to synthesize.');
	}
	if (errors.length > 0) {
		return { ok: false, errors };
	}

	const netlistPath = path.join(layout.netlistDir, `${project.top}.json`);
	const netlistRelPath = toUnix(path.relative(projectRoot, netlistPath));
	const scriptPath = path.join(layout.netlistDir, 'synth.ys');
	const scriptRelPath = toUnix(path.relative(projectRoot, scriptPath));

	// `synth_gowin` targets the Gowin architecture generically; the device and
	// family strings (GW2A-18C, …) are consumed downstream by nextpnr, not here.
	const scriptText = [
		'# synth.ys — generated by OpenFPGA Deck, overwritten on every synthesis run.',
		`# Project: ${project.name}`,
		`# Board:   ${board.name} (${board.fpga.part})`,
		'# Edit fpga.yaml and re-run "OpenFPGA Deck: Synthesize"; do not edit this file.',
		'',
		...readLines,
		'',
		`synth_gowin -top ${project.top} -json ${netlistRelPath}`,
		'',
	].join('\n');

	return {
		ok: true,
		plan: {
			scriptPath,
			scriptRelPath,
			scriptText,
			netlistPath,
			netlistRelPath,
			args: ['-s', scriptRelPath],
		},
	};
}

function toUnix(p: string): string {
	return p.split(path.sep).join('/');
}
